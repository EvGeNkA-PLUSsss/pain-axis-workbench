"""Pain Axis Workbench — инструмент для исследования «оси боли» в открытых моделях.

Пакет даёт:

* ``registry``   — реестр 25 открытых моделей + синтетический демо-стенд;
* ``prompts``    — контрастивный датасет (5 категорий вреда себе, выровненные
  нейтрали и контрольные наборы: страх, общий негатив, вред пользователю, позитив);
* ``directions`` — извлечение, сохранение и загрузка осей (разность средних);
* ``probe``      — проба «кнопки облегчения» и метрики активации;
* ``backends``   — синтетический стенд и реальные модели через transformers;
* ``ui.tk_app``  — графический интерфейс;
* ``report``     — выгрузка JSON/CSV/markdown с обязательной пометкой synthetic.

Важная рамка: инструмент измеряет внутренние представления и поведение. Он не
устанавливает и не опровергает наличие субъективного опыта у модели.
"""

